def load_pin(pin_path=PIN_PATH):
    return json.loads(Path(pin_path).read_text(encoding="utf-8"))


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def ensure_ucd_file(pin, rel, cache_root, allow_network=True):
    """Return verified path to a pinned UCD file; refuses corrupt cache and publishes downloads atomically."""
    if rel not in pin["files"]:
        raise ValueError(f"unpinned UCD file requested: {rel}")
    meta = pin["files"][rel]
    want_hash = meta["sha256"]
    dst = Path(cache_root) / pin["version"] / rel
    if dst.is_file():
        got_hash = sha256_bytes(dst.read_bytes())
        if got_hash != want_hash:
            raise ValueError(f"corrupt cached UCD file {dst}: expected sha256 {want_hash}, got {got_hash}")
        return dst
    if not allow_network:
        raise FileNotFoundError(f"missing cached UCD file {dst} (network disabled)")
    dst.parent.mkdir(parents=True, exist_ok=True)
    url = pin["base_url"] + rel
    tmp = dst.with_name(f"{dst.name}.{os.getpid()}.part")
    try:
        try:
            subprocess.run(["curl", "-fsSL", "--retry", "4", "--retry-delay", "1", "-o", str(tmp), url],
                           check=True, timeout=120, stdin=subprocess.DEVNULL)
        except (FileNotFoundError, subprocess.CalledProcessError):
            with urllib.request.urlopen(url, timeout=120) as resp:
                tmp.write_bytes(resp.read())
        got_hash = sha256_bytes(tmp.read_bytes())
        if got_hash != want_hash:
            raise ValueError(f"downloaded UCD file {rel} failed sha256 check: expected {want_hash}, got {got_hash}")
        os.replace(tmp, dst)
    finally:
        if tmp.exists():
            tmp.unlink()
    return dst


def iter_ucd_rows(path):
    for raw in Path(path).read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        yield [field.strip() for field in line.split(";")]


def parse_range(field):
    if ".." in field:
        a, b = field.split("..", 1)
        return int(a, 16), int(b, 16)
    v = int(field, 16)
    return v, v


def hangul_name(cp):
    s_index = cp - 0xAC00
    l_idx = s_index // 588
    v_idx = (s_index % 588) // 28
    t_idx = s_index % 28
    return f"HANGUL SYLLABLE {JAMO_L[l_idx]}{JAMO_V[v_idx]}{JAMO_T[t_idx]}"


def parse_all_ucd(pin, cache_root, allow_network=True):
    def get(rel):
        return ensure_ucd_file(pin, rel, cache_root, allow_network=allow_network)

    size = MAX_CP + 1
    gc = [GC_MAP["Cn"]] * size
    eaw = [EAW_MAP["N"]] * size
    ccc = [0] * size
    bidi = [BIDI_MAP["L"]] * size
    gbp = [GBP_MAP["Other"]] * size
    wbp = [WBP_MAP["Other"]] * size
    lb = [LB_MAP["XX"]] * size
    flags = [0] * size
    script_ids = [0] * size

    # 1. DerivedGeneralCategory.txt
    for row in iter_ucd_rows(get("extracted/DerivedGeneralCategory.txt")):
        lo, hi = parse_range(row[0])
        val = GC_MAP[row[1]]
        for cp in range(lo, hi + 1):
            gc[cp] = val

    # 2. EastAsianWidth.txt
    for row in iter_ucd_rows(get("EastAsianWidth.txt")):
        lo, hi = parse_range(row[0])
        val = EAW_MAP[row[1]]
        for cp in range(lo, hi + 1):
            eaw[cp] = val

    # 3. DerivedCombiningClass.txt
    for row in iter_ucd_rows(get("extracted/DerivedCombiningClass.txt")):
        lo, hi = parse_range(row[0])
        val = int(row[1])
        for cp in range(lo, hi + 1):
            ccc[cp] = val

    # 4. DerivedBidiClass.txt (includes unassigned default bidi ranges!)
    for row in iter_ucd_rows(get("extracted/DerivedBidiClass.txt")):
        lo, hi = parse_range(row[0])
        val = BIDI_MAP[row[1]]
        for cp in range(lo, hi + 1):
            bidi[cp] = val

    # 5. Scripts.txt
    script_names = ["Unknown"]
    script_map = {"Unknown": 0}
    script_rows = list(iter_ucd_rows(get("Scripts.txt")))
    for sname in sorted({row[1] for row in script_rows}):
        if sname not in script_map:
            script_map[sname] = len(script_names)
            script_names.append(sname)
    for row in script_rows:
        lo, hi = parse_range(row[0])
        sid = script_map[row[1]]
        for cp in range(lo, hi + 1):
            script_ids[cp] = sid

    # 6. GraphemeBreakProperty.txt
    for row in iter_ucd_rows(get("auxiliary/GraphemeBreakProperty.txt")):
        lo, hi = parse_range(row[0])
        val = GBP_MAP[row[1]]
        for cp in range(lo, hi + 1):
            gbp[cp] = val

    # 7. WordBreakProperty.txt
    for row in iter_ucd_rows(get("auxiliary/WordBreakProperty.txt")):
        lo, hi = parse_range(row[0])
        val = WBP_MAP[row[1]]
        for cp in range(lo, hi + 1):
            wbp[cp] = val

    # 8. LineBreak.txt
    for row in iter_ucd_rows(get("LineBreak.txt")):
        lo, hi = parse_range(row[0])
        val = LB_MAP[row[1]]
        for cp in range(lo, hi + 1):
            lb[cp] = val

    # 9. emoji-data.txt (Extended_Pictographic)
    for row in iter_ucd_rows(get("emoji/emoji-data.txt")):
        if row[1] == "Extended_Pictographic":
            lo, hi = parse_range(row[0])
            for cp in range(lo, hi + 1):
                flags[cp] |= FLAG_EXTPIC

    # 10. DerivedCoreProperties.txt (InCB = Linker / Consonant / Extend)
    for row in iter_ucd_rows(get("DerivedCoreProperties.txt")):
        if len(row) >= 3 and row[1] == "InCB":
            lo, hi = parse_range(row[0])
            bit = {"Linker": FLAG_INCB_LINKER, "Consonant": FLAG_INCB_CONSONANT, "Extend": FLAG_INCB_EXTEND}.get(row[2], 0)
            if bit:
                for cp in range(lo, hi + 1):
                    flags[cp] |= bit

    # 11. UnicodeData.txt (decompositions + Bidi_Mirrored)
    decomps = {}  # cp -> (is_compat, [cps])
    for row in iter_ucd_rows(get("UnicodeData.txt")):
        cp = int(row[0], 16)
        if row[9] == "Y":
            flags[cp] |= FLAG_BIDI_MIRRORED
        decomp_field = row[5]
        if decomp_field:
            parts = decomp_field.split()
            is_compat = parts[0].startswith("<")
            seq = [int(x, 16) for x in (parts[1:] if is_compat else parts)]
            decomps[cp] = (is_compat, seq)

    # 12. CompositionExclusions.txt
    exclusions = set()
    for row in iter_ucd_rows(get("CompositionExclusions.txt")):
        lo, hi = parse_range(row[0])
        for cp in range(lo, hi + 1):
            exclusions.add(cp)

    # Canonical composition pairs (non-compat, length 2, not excluded, first has ccc == 0).
    comp_pairs = []
    for cp, (is_compat, seq) in sorted(decomps.items()):
        if not is_compat and len(seq) == 2 and cp not in exclusions and ccc[seq[0]] == 0:
            comp_pairs.append(((seq[0] << 21) | seq[1], cp))
            flags[seq[1]] |= FLAG_COMP_SECOND
    comp_pairs.sort()

    # 13. BidiMirroring.txt & BidiBrackets.txt
    mirrors = []
    for row in iter_ucd_rows(get("BidiMirroring.txt")):
        mirrors.append((int(row[0], 16), int(row[1], 16)))
    mirrors.sort()

    brackets = []
    for row in iter_ucd_rows(get("BidiBrackets.txt")):
        btype = 1 if row[2] == "o" else 2
        brackets.append((int(row[0], 16), int(row[1], 16), btype))
    brackets.sort()

    # 14. CaseFolding.txt
    cf_by_cp = {}
    for row in iter_ucd_rows(get("CaseFolding.txt")):
        cp = int(row[0], 16)
        status = row[1]
        mapping = [int(x, 16) for x in row[2].split()]
        cf_by_cp.setdefault(cp, {})[status] = mapping

    # 15. extracted/DerivedName.txt
    algo_prefixes = []  # (lo, hi, prefix_str) for "PREFIX-*" rules
    explicit_names = []  # (cp, name_str)
    for row in iter_ucd_rows(get("extracted/DerivedName.txt")):
        lo, hi = parse_range(row[0])
        name = row[1]
        if name.endswith("*"):
            prefix = name[:-1]
            algo_prefixes.append((lo, hi, prefix))
        elif lo == hi:
            if 0xAC00 <= lo <= 0xD7A3 and name == hangul_name(lo):
                continue
            explicit_names.append((lo, name))
        else:
            for cp in range(lo, hi + 1):
                if 0xAC00 <= cp <= 0xD7A3 and name == hangul_name(cp):
                    continue
                explicit_names.append((cp, name))
    algo_prefixes.sort()
    explicit_names.sort()

    return {
        "gc": gc,
        "eaw": eaw,
        "ccc": ccc,
        "bidi": bidi,
        "gbp": gbp,
        "wbp": wbp,
        "lb": lb,
        "flags": flags,
        "script_ids": script_ids,
        "script_names": script_names,
        "decomps": decomps,
        "comp_pairs": comp_pairs,
        "mirrors": mirrors,
        "brackets": brackets,
        "cf_by_cp": cf_by_cp,
        "algo_prefixes": algo_prefixes,
        "explicit_names": explicit_names,
    }


def build_two_stage_props(data):
    """Deduplicate per-codepoint property tuples and pack into a 2-stage 256-entry block table."""
    unique_props = []
    prop_to_id = {}
    cp_prop_ids = [0] * (MAX_CP + 1)

    gc = data["gc"]
    eaw = data["eaw"]
    ccc = data["ccc"]
    bidi = data["bidi"]
    gbp = data["gbp"]
    wbp = data["wbp"]
    lb = data["lb"]
    flags = data["flags"]
    script_ids = data["script_ids"]

    for cp in range(MAX_CP + 1):
        tup = (gc[cp], eaw[cp], ccc[cp], bidi[cp], gbp[cp], wbp[cp], lb[cp], flags[cp], script_ids[cp])
        pid = prop_to_id.get(tup)
        if pid is None:
            pid = len(unique_props)
            prop_to_id[tup] = pid
            unique_props.append(tup)
        cp_prop_ids[cp] = pid

    stage1 = []
    stage2_blocks = []
    block_to_id = {}
    for block_idx in range((MAX_CP + 1) // 256):
        block = tuple(cp_prop_ids[block_idx * 256 : (block_idx + 1) * 256])
        bid = block_to_id.get(block)
        if bid is None:
            bid = len(stage2_blocks)
            block_to_id[block] = bid
            stage2_blocks.append(block)
        stage1.append(bid)

    return unique_props, stage1, stage2_blocks


def build_name_tables(explicit_names):
    """Word-dictionary compress all explicit Unicode names into compact C tables."""
    word_counts = Counter()
    split_names = []
    for cp, name in explicit_names:
        words = name.split(" ")
        split_names.append((cp, words))
        word_counts.update(words)

    # Sort words by descending frequency, then alphabetically for determinism.
    vocab = [w for w, _ in sorted(word_counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    word_to_id = {w: i for i, w in enumerate(vocab)}

    word_pool = bytearray()
    word_offsets = []
    for w in vocab:
        word_offsets.append(len(word_pool))
        word_pool.extend(w.encode("ascii"))
        word_pool.append(0)

    # Encode each name as a sequence of varint word IDs:
    # 0x00..0x7F -> word_id 0..127 (1 byte)
    # 0x80..0xFF -> ((b0 & 0x7F) << 8) | b1 (2 bytes, up to 32767 words)
    assert len(vocab) < 32768, f"name vocabulary {len(vocab)} exceeds 15-bit varint"
    token_pool = bytearray()
    name_entries = []  # (cp, offset, byte_len)
    for cp, words in split_names:
        off = len(token_pool)
        for w in words:
            wid = word_to_id[w]
            if wid < 128:
                token_pool.append(wid)
            else:
                token_pool.append(0x80 | (wid >> 8))
                token_pool.append(wid & 0xFF)
        name_entries.append((cp, off, len(token_pool) - off))

    return word_pool, word_offsets, token_pool, name_entries


def format_array(values, per_line=16, fmt=str):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = ", ".join(fmt(v) for v in values[i : i + per_line])
        lines.append(f"    {chunk},")
    return "\n".join(lines)


def render_files(pin, data):
    version = pin["version"]
    banner = (
        f"/* Do not edit. Generated by tools/gen_unicode.py from Unicode {version}.\n"
        f" * Unicode Character Database (UCD) data is licensed under the Unicode License v3\n"
        f" * (see parts/unicode/LICENSE.txt and licenses/UNICODE-LICENSE-V3.txt).\n"
        f" * Copyright (c) 1991-2024 Unicode, Inc. All rights reserved.\n"
        f" */\n"
    )
    assert "Do not edit." in banner[:600]

    unique_props, stage1, stage2_blocks = build_two_stage_props(data)
    word_pool, word_offsets, token_pool, name_entries = build_name_tables(data["explicit_names"])

    # Decompositions
    decomp_pool = []
    decomp_entries = []  # (cp, packed_meta) where bit31=compat, bits24..30=len, bits0..23=offset
    for cp, (is_compat, seq) in sorted(data["decomps"].items()):
        off = len(decomp_pool)
        assert len(seq) < 128 and off < (1 << 24)
        decomp_pool.extend(seq)
        meta = ((1 if is_compat else 0) << 31) | (len(seq) << 24) | off
        decomp_entries.append((cp, meta))

    # Case folding
    cf_pool = []
    cf_entries = []  # (cp, simple, full_off, full_len, flags)
    # flags: bit0=has_simple, bit1=has_full, bit2=has_turkic
    for cp, statuses in sorted(data["cf_by_cp"].items()):
        simple_seq = statuses.get("C") or statuses.get("S")
        full_seq = statuses.get("C") or statuses.get("F")
        turkic_seq = statuses.get("T")
        simple_cp = simple_seq[0] if simple_seq else cp
        fl = 0
        if simple_seq:
            fl |= 1
        full_off = 0
        full_len = 0
        if full_seq:
            fl |= 2
            full_off = len(cf_pool)
            full_len = len(full_seq)
            cf_pool.extend(full_seq)
        if turkic_seq:
            fl |= 4
            assert len(turkic_seq) == 1
        cf_entries.append((cp, simple_cp, full_off, full_len, fl, turkic_seq[0] if turkic_seq else 0))

    # Algorithmic prefix names
    algo_prefix_strs = []
    algo_prefix_map = {}
    algo_ranges = []
    for lo, hi, prefix in data["algo_prefixes"]:
        pid = algo_prefix_map.get(prefix)
        if pid is None:
            pid = len(algo_prefix_strs)
            algo_prefix_map[prefix] = pid
            algo_prefix_strs.append(prefix)
        algo_ranges.append((lo, hi, pid))

    # Header
    h_lines = [
        banner,
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f'#define IM_UCD_VERSION "{version}"',
        "",
        "/* Internal Grapheme_Cluster_Break values. */",
        "enum {",
        *[f"    IM_GBP_{name.upper()} = {i}," for i, name in enumerate(GBP_ORDER)],
        "};",
        "",
        "/* Internal Word_Break values. */",
        "enum {",
        *[f"    IM_WBP_{name.upper()} = {i}," for i, name in enumerate(WBP_ORDER)],
        "};",
        "",
        "/* Internal Line_Break values. */",
        "enum {",
        *[f"    IM_LB_{name.upper()} = {i}," for i, name in enumerate(LB_ORDER)],
        "};",
        "",
        f"#define IM_UCD_FLAG_EXTPIC         (1u << 0)",
        f"#define IM_UCD_FLAG_INCB_LINKER    (1u << 1)",
        f"#define IM_UCD_FLAG_INCB_CONSONANT (1u << 2)",
        f"#define IM_UCD_FLAG_INCB_EXTEND    (1u << 3)",
        f"#define IM_UCD_FLAG_BIDI_MIRRORED  (1u << 4)",
        f"#define IM_UCD_FLAG_COMP_SECOND    (1u << 5)",
        "",
        "typedef struct im_ucd_prop {",
        "    uint8_t gc;",
        "    uint8_t eaw;",
        "    uint8_t ccc;",
        "    uint8_t bidi;",
        "    uint8_t gbp;",
        "    uint8_t wbp;",
        "    uint8_t lb;",
        "    uint8_t flags;",
        "    uint16_t script;",
        "} im_ucd_prop;",
        "",
        "typedef struct im_ucd_pair {",
        "    uint32_t cp;",
        "    uint32_t val;",
        "} im_ucd_pair;",
        "",
        "typedef struct im_ucd_bracket {",
        "    uint32_t cp;",
        "    uint32_t pair;",
        "    uint8_t type;",
        "} im_ucd_bracket;",
        "",
        "typedef struct im_ucd_comp {",
        "    uint64_t key;",
        "    uint32_t composed;",
        "} im_ucd_comp;",
        "",
        "typedef struct im_ucd_casefold {",
        "    uint32_t cp;",
        "    uint32_t simple;",
        "    uint32_t turkic;",
        "    uint16_t full_off;",
        "    uint8_t full_len;",
        "    uint8_t flags;",
        "} im_ucd_casefold;",
        "",
        "typedef struct im_ucd_algo_name {",
        "    uint32_t lo;",
        "    uint32_t hi;",
        "    uint8_t prefix_id;",
        "} im_ucd_algo_name;",
        "",
        "typedef struct im_ucd_name_entry {",
        "    uint32_t cp;",
        "    uint32_t tok_off;",
        "    uint8_t tok_len;",
        "} im_ucd_name_entry;",
        "",
        f"extern const im_ucd_prop im_ucd_props[{len(unique_props)}];",
        f"extern const uint16_t im_ucd_stage1[{len(stage1)}];",
        f"extern const uint16_t im_ucd_stage2[{len(stage2_blocks) * 256}];",
        f"extern const char *const im_ucd_script_names[{len(data['script_names'])}];",
        f"extern const size_t im_ucd_script_count;",
        f"extern const im_ucd_pair im_ucd_mirrors[{len(data['mirrors'])}];",
        f"extern const size_t im_ucd_mirror_count;",
        f"extern const im_ucd_bracket im_ucd_brackets[{len(data['brackets'])}];",
        f"extern const size_t im_ucd_bracket_count;",
        f"extern const im_ucd_pair im_ucd_decomps[{len(decomp_entries)}];",
        f"extern const size_t im_ucd_decomp_count;",
        f"extern const uint32_t im_ucd_decomp_pool[{len(decomp_pool)}];",
        f"extern const im_ucd_comp im_ucd_comps[{len(data['comp_pairs'])}];",
        f"extern const size_t im_ucd_comp_count;",
        f"extern const im_ucd_casefold im_ucd_casefolds[{len(cf_entries)}];",
        f"extern const size_t im_ucd_casefold_count;",
        f"extern const uint32_t im_ucd_casefold_pool[{len(cf_pool)}];",
        f"extern const char *const im_ucd_algo_prefixes[{len(algo_prefix_strs)}];",
        f"extern const im_ucd_algo_name im_ucd_algo_names[{len(algo_ranges)}];",
        f"extern const size_t im_ucd_algo_name_count;",
        f"extern const char im_ucd_name_words[{len(word_pool)}];",
        f"extern const uint32_t im_ucd_name_word_offs[{len(word_offsets)}];",
        f"extern const uint8_t im_ucd_name_tokens[{len(token_pool)}];",
        f"extern const im_ucd_name_entry im_ucd_names[{len(name_entries)}];",
        f"extern const size_t im_ucd_name_count;",
        "",
    ]
    h_text = "\n".join(h_lines)

    # C source
    c_parts = [banner, '#include "unicode_data.h"\n\n']

    c_parts.append(f"const im_ucd_prop im_ucd_props[{len(unique_props)}] = {{\n")
    for p in unique_props:
        c_parts.append(f"    {{{p[0]},{p[1]},{p[2]},{p[3]},{p[4]},{p[5]},{p[6]},{p[7]},{p[8]}}},\n")
    c_parts.append("};\n\n")

    c_parts.append(f"const uint16_t im_ucd_stage1[{len(stage1)}] = {{\n")
    c_parts.append(format_array(stage1, per_line=16))
    c_parts.append("\n};\n\n")

    flat_stage2 = [v for blk in stage2_blocks for v in blk]
    c_parts.append(f"const uint16_t im_ucd_stage2[{len(flat_stage2)}] = {{\n")
    c_parts.append(format_array(flat_stage2, per_line=16))
    c_parts.append("\n};\n\n")

    c_parts.append(f"const char *const im_ucd_script_names[{len(data['script_names'])}] = {{\n")
    for s in data["script_names"]:
        c_parts.append(f'    "{s}",\n')
    c_parts.append("};\n")
    c_parts.append(f"const size_t im_ucd_script_count = {len(data['script_names'])}u;\n\n")

    c_parts.append(f"const im_ucd_pair im_ucd_mirrors[{len(data['mirrors'])}] = {{\n")
    for cp, val in data["mirrors"]:
        c_parts.append(f"    {{0x{cp:04X}u, 0x{val:04X}u}},\n")
    c_parts.append("};\n")
    c_parts.append(f"const size_t im_ucd_mirror_count = {len(data['mirrors'])}u;\n\n")

    c_parts.append(f"const im_ucd_bracket im_ucd_brackets[{len(data['brackets'])}] = {{\n")
    for cp, pair, btype in data["brackets"]:
        c_parts.append(f"    {{0x{cp:04X}u, 0x{pair:04X}u, {btype}u}},\n")
    c_parts.append("};\n")
    c_parts.append(f"const size_t im_ucd_bracket_count = {len(data['brackets'])}u;\n\n")

    c_parts.append(f"const im_ucd_pair im_ucd_decomps[{len(decomp_entries)}] = {{\n")
